//! `markdown-catalog`: the reference target, a Markdown catalogue of the model over any pack.
//!
//! One file (`catalog.md`, or `options.file`) with a section per element type (the pack's label,
//! a table of the elements with identifier, tag, name, owner and the type's declared properties),
//! a relationships table and a Notes section with one protected region per element for text
//! written by hand. Every table row and note heading is followed by `<!-- vizcraft:id=<id> -->`
//! so each line traces back to its element or relationship.
//!
//! Options: `title` (the heading, default "Model catalogue"), `file` (the output path),
//! `notes` (default true; false leaves out the Notes section), and the shared `flatten`, which
//! writes port ends as `identifier.port` in the relationships table.

use std::fmt::Write as _;

use crate::names::{Case, NameRules, Names};
use crate::regions;
use crate::target::{Construct, ModelView, Options, Output, Support, Target, emits};
use crate::{CodegenError, clip};

/// The Markdown catalogue target.
pub struct MarkdownCatalog;

/// Comment syntax of the regions and trace comments.
const OPEN: &str = "<!--";
const CLOSE: &str = "-->";

/// Longest text put in one table cell, in bytes.
const MAX_CELL: usize = 400;

impl Target for MarkdownCatalog {
    fn id(&self) -> &'static str {
        "markdown-catalog"
    }

    fn label(&self) -> &'static str {
        "Markdown Catalogue"
    }

    fn single_file(&self) -> bool {
        true
    }

    fn support(&self) -> Vec<(Construct, Support)> {
        vec![
            (Construct::Element, Support::Supported),
            (Construct::Property, Support::Supported),
            (Construct::Relationship, Support::Supported),
            (Construct::Containment, Support::Supported),
            (Construct::Port, Support::Flattened),
        ]
    }

    fn comment(&self) -> (&'static str, &'static str) {
        (OPEN, CLOSE)
    }

    fn name_rules(&self) -> NameRules {
        NameRules { case: Case::Kebab, max_len: 64, reserved: &[], digit_prefix: None, fallback: "element" }
    }

    fn generate(&self, view: &ModelView, names: &Names, options: &Options) -> Result<Vec<Output>, CodegenError> {
        let path = options.str("file").unwrap_or("catalog.md").to_string();
        crate::writer::relative_path(&path)?;
        let title = options.str("title").map(cell).filter(|t| !t.is_empty()).unwrap_or_else(|| "Model catalogue".to_string());
        let mut s = String::new();
        let _ = writeln!(s, "# {title}");
        s.push('\n');
        let _ = writeln!(
            s,
            "{OPEN} Generated by VizCraft (markdown-catalog). Write by hand only between vizcraft:begin and vizcraft:end; other edits are merged on the next run. {CLOSE}"
        );
        if view.elements.is_empty() {
            s.push('\n');
            s.push_str("No elements in scope.\n");
            return Ok(vec![Output { path, text: s }]);
        }
        let owners = emits(self, Construct::Containment, options);
        for type_id in view.element_types() {
            let elements: Vec<_> = view.elements.iter().filter(|e| e.type_id == type_id).collect();
            let props = view.declared_properties(type_id);
            let with_owner = owners && elements.iter().any(|e| e.owner.as_deref().is_some_and(|o| view.contains(o)));
            s.push('\n');
            let _ = writeln!(s, "## {} ({})", cell(&view.type_label(type_id)), cell(&view.pack_label(type_id)));
            s.push('\n');
            let mut head = vec!["Identifier".to_string(), "Tag".to_string(), "Name".to_string()];
            if with_owner {
                head.push("Owner".to_string());
            }
            head.extend(props.iter().map(|(_, label)| cell(label)));
            let _ = writeln!(s, "| {} |", head.join(" | "));
            let _ = writeln!(s, "|{}", "---|".repeat(head.len()));
            for e in elements {
                let mut row = vec![cell(names.ident(&e.id)), cell(&e.tag), cell(&e.name)];
                if with_owner {
                    row.push(e.owner.as_deref().filter(|o| view.contains(o)).map(|o| cell(names.ident(o))).unwrap_or_default());
                }
                for (key, _) in &props {
                    row.push(e.prop(key).map(|v| cell(&v.display())).unwrap_or_default());
                }
                let _ = writeln!(s, "| {} |{}", row.join(" | "), trace(&e.id));
            }
        }
        if !view.relationships.is_empty() {
            let ports = emits(self, Construct::Port, options);
            s.push('\n');
            s.push_str("## Relationships\n\n");
            s.push_str("| Type | From | To | Name | Properties |\n|---|---|---|---|---|\n");
            for r in &view.relationships {
                let end = |id: &str, port: &Option<String>| {
                    let base = cell(names.ident(id));
                    match port.as_deref().filter(|_| ports) {
                        Some(p) => format!("{base}.{}", cell(p)),
                        None => base,
                    }
                };
                let props: Vec<String> = r.properties.iter().map(|(k, v)| format!("{}={}", cell(k), cell(&v.display()))).collect();
                let _ = writeln!(
                    s,
                    "| {} | {} | {} | {} | {} |{}",
                    cell(&view.type_label(&r.type_id)),
                    end(&r.source, &r.source_port),
                    end(&r.target, &r.target_port),
                    cell(&r.name),
                    props.join(", "),
                    trace(&r.id)
                );
            }
        }
        if options.bool("notes").unwrap_or(true) {
            s.push('\n');
            s.push_str("## Notes\n");
            for e in &view.elements {
                let id = comment_id(&e.id);
                s.push('\n');
                let _ = writeln!(s, "### {}", cell(names.ident(&e.id)));
                let _ = writeln!(s, "{}", trace(&e.id));
                let _ = writeln!(s, "{}", regions::begin(&id, OPEN, CLOSE));
                let _ = writeln!(s, "{}", regions::end(&id, OPEN, CLOSE));
            }
        }
        Ok(vec![Output { path, text: s }])
    }
}

/// `<!-- vizcraft:id=<id> -->` for an element or relationship id.
fn trace(id: &str) -> String {
    format!("{OPEN} vizcraft:id={} {CLOSE}", comment_id(id))
}

/// An id safe inside an HTML comment and a region marker: letters, digits and `._:/@+` stay, and
/// every other byte (spaces, dashes, angle brackets) is written as `%XX`.
pub fn comment_id(id: &str) -> String {
    let mut out = String::with_capacity(id.len());
    for b in clip(id, 200).bytes() {
        if b.is_ascii_alphanumeric() || b"._:/@+".contains(&b) {
            out.push(char::from(b));
        } else {
            let _ = write!(out, "%{b:02X}");
        }
    }
    out
}

/// Text for one table cell or heading: one line, at most [`MAX_CELL`] bytes, with pipes escaped
/// and `&`, `<` and `>` written as entities so no name can open HTML or close a trace comment.
fn cell(text: &str) -> String {
    let one_line: String = clip(text, MAX_CELL).chars().map(|c| if c.is_control() { ' ' } else { c }).collect();
    one_line.trim().replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('|', "\\|")
}
